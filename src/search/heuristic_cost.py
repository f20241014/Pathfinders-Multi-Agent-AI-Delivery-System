"""Measure where A*'s run time goes, on the same 200 OD pairs as src/search/benchmark.py.

(1) How many times A* calls the heuristic per pair (the heuristic is wrapped in a counter;
    astar.py itself is not changed).
(2) Microseconds per heuristic call and per free-flow edge-cost lookup (the cost function
    the static searches use), each over many calls after a warm-up. An empty loop over the
    same inputs is timed too, because the loop itself also takes time.
(3) Mean run time of Dijkstra, A*, and A* with the heuristic precomputed for the target
    (so each call is a dictionary lookup), timed pair by pair in the same run.

Run from the repo root:
    python -m src.search.heuristic_cost [--pairs 200] [--seed 42] [--calls 100000]
Appends (or replaces) the section "Where A*'s time goes (measured)" at the end of
docs/benchmark_dijkstra_astar.md.
"""
import argparse
import platform
import time

import numpy as np

from src.search.astar import astar
from src.search.benchmark import MD_PATH, MEASURED_HEADER, WARMUP_PAIRS, random_od_pairs
from src.search.dijkstra import dijkstra, free_flow_cost
from src.search.heuristics import make_heuristic


def count_calls(G, pairs, h):
    """Heuristic calls made by one A* run, for each pair."""
    counts = []
    for s, t in pairs:
        calls = [0]

        def counting_h(node, goal):
            calls[0] += 1
            return h(node, goal)
        astar(G, s, t, heuristic=counting_h)
        counts.append(calls[0])
    return counts


def us_per_call(fn, inputs, warmup=1000):
    """Mean microseconds of fn(*args) over `inputs`, after `warmup` untimed calls."""
    for args in inputs[:warmup]:
        fn(*args)
    start = time.perf_counter()
    for args in inputs:
        fn(*args)
    return (time.perf_counter() - start) / len(inputs) * 1e6


def us_empty_loop(inputs):
    """Microseconds per step of the same loop with no call in it (loop overhead)."""
    start = time.perf_counter()
    for args in inputs:
        pass
    return (time.perf_counter() - start) / len(inputs) * 1e6


def time_three(G, pairs, h):
    """Milliseconds per pair for Dijkstra, A* and A* with a precomputed heuristic."""
    tables = {t: {n: h(n, t) for n in G.nodes} for _, t in pairs}   # built before timing
    for s, t in pairs[:WARMUP_PAIRS]:                                 # warm-up, not recorded
        dijkstra(G, s, t)
        astar(G, s, t, heuristic=h)
        astar(G, s, t, heuristic=lambda n, goal: tables[goal][n])

    ms = {"dijkstra": [], "astar": [], "astar_cached": []}
    for s, t in pairs:
        table = tables[t]
        runs = [("dijkstra", lambda: dijkstra(G, s, t)),
                ("astar", lambda: astar(G, s, t, heuristic=h)),
                ("astar_cached", lambda: astar(G, s, t, heuristic=lambda n, goal: table[n]))]
        costs = []
        for name, search in runs:
            start = time.perf_counter()
            result = search()
            ms[name].append((time.perf_counter() - start) * 1000)
            costs.append(result.cost)
        if max(costs) - min(costs) > 1e-6:
            raise AssertionError(f"different costs for {s} -> {t}: {costs}")
    return ms


def measure(G, pairs, n_calls, seed):
    """Run (1), (2) and (3); return the numbers in a dict."""
    h = make_heuristic(G)
    rng = np.random.default_rng(seed)
    nodes = list(G.nodes)
    edges = list(G.edges(data=True))
    h_inputs = [(nodes[i], nodes[j]) for i, j in rng.integers(len(nodes), size=(n_calls, 2))]
    e_inputs = [edges[i] for i in rng.integers(len(edges), size=n_calls)]

    calls = count_calls(G, pairs, h)
    ms = time_three(G, pairs, h)
    return {
        "pairs": len(pairs), "n_calls": n_calls, "seed": seed,
        "calls_mean": float(np.mean(calls)), "calls_median": float(np.median(calls)),
        "us_heuristic": us_per_call(h, h_inputs),
        "us_edge_cost": us_per_call(free_flow_cost, e_inputs),
        "us_empty_loop": us_empty_loop(h_inputs),
        "ms_mean": {name: float(np.mean(v)) for name, v in ms.items()},
    }


def write_section(res, path=MD_PATH):
    """Replace (or add) the measured section at the end of the benchmark doc."""
    m = res["ms_mean"]
    lines = [
        MEASURED_HEADER,
        "",
        f"Generated by `python -m src.search.heuristic_cost --pairs {res['pairs']} --seed "
        f"{res['seed']} --calls {res['n_calls']}` on {platform.platform()}, Python "
        f"{platform.python_version()}. Same OD pairs as above; the run times here come from "
        "a new run, so they differ slightly from the tables above. All times are "
        "machine-specific.",
        "",
        "| Measurement | Value |",
        "| --- | --- |",
        f"| Heuristic calls per A* run, mean | {res['calls_mean']:.0f} |",
        f"| Heuristic calls per A* run, median | {res['calls_median']:.0f} |",
        f"| One heuristic call ({res['n_calls']:,} calls) | {res['us_heuristic']:.3f} us |",
        f"| One free-flow edge-cost lookup ({res['n_calls']:,} calls) | "
        f"{res['us_edge_cost']:.3f} us |",
        f"| Empty loop over the same inputs (overhead in both rows above) | "
        f"{res['us_empty_loop']:.3f} us |",
        f"| Dijkstra, mean run time | {m['dijkstra']:.2f} ms |",
        f"| A*, mean run time | {m['astar']:.2f} ms |",
        f"| A* with the heuristic precomputed for the target, mean run time | "
        f"{m['astar_cached']:.2f} ms |",
        "",
        "What the numbers show: how often A* calls the heuristic, how long one call and one "
        "edge-cost lookup take on this machine, and how A*'s mean run time changes when each "
        "heuristic call becomes a dictionary lookup (same pairs, same expansions, same costs). "
        "Precomputing the table is not included in that time; it is not a fair way to run A* "
        "for one trip, only a way to remove the heuristic's cost from the measurement.",
        "",
        "What they do not prove: they are means of single runs on the one machine named above "
        "(OS and Python version) and would differ on other machines or Python versions; they "
        "do not show "
        "how the rest of A*'s time is split (heap operations, dictionary updates); and a "
        "faster heuristic implementation was not tried.",
        "",
    ]
    old = path.read_text(encoding="utf-8")
    if MEASURED_HEADER in old:
        old = old[:old.index(MEASURED_HEADER)].rstrip("\n") + "\n"
    path.write_text(old + "\n" + "\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--pairs", type=int, default=200)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--calls", type=int, default=100_000)
    args = parser.parse_args()

    from src.world.graph_loader import load_road_graph
    G = load_road_graph("secunderabad")
    res = measure(G, random_od_pairs(G, args.pairs, args.seed), args.calls, args.seed)
    for key, value in res.items():
        print(f"{key}: {value}")
    write_section(res)
    print(f"Updated {MD_PATH}")


if __name__ == "__main__":
    main()
