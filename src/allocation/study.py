"""Reproducible R4 time-limit study: raw CSV + derived Markdown table.

Synthetic static benchmark, NOT the main disruption sweep or Hyderabad validation.
"""
import argparse
import csv
from dataclasses import replace
import hashlib
import json
from pathlib import Path
import random
from time import perf_counter

from src.allocation.central_vrp import CentralVRP
from src.allocation.contract_net import ContractNet
from src.allocation.cost_model import VehicleState, priority_weight, schedule
from src.allocation.quality import exact_objective
from src.sim.models import Order, Vehicle


LIMITS = [0.1, 0.5, 2.0]
SEEDS = [101, 202, 303]  # R4 pilot-only; never reuse for the main test sweep


def fixture(seed, count):
    rng = random.Random(seed)
    points = [(rng.randrange(30), rng.randrange(30)) for _ in range(count + 1)]
    orders = [Order(str(i), i, rng.randint(1, 3), priority=rng.randint(1, 3),
                    tw_start=0, tw_end=20000, service_time=2)
              for i in range(1, count + 1)]
    fleet = 2 if count <= 6 else 5
    states = [VehicleState(Vehicle(str(i), 0, max(8, count), 0)) for i in range(fleet)]

    def travel(vehicle, a, b):
        return (abs(points[a][0]-points[b][0]) + abs(points[a][1]-points[b][1])) * 5

    return states, orders, travel


def run_study(output='reports/r4'):
    out = Path(output)
    out.mkdir(parents=True, exist_ok=True)
    rows = []
    for count in (4, 30):
        for seed in SEEDS:
            states, orders, travel = fixture(seed, count)
            copies = [replace(s, vehicle=replace(s.vehicle), orders=[]) for s in states]
            cnp = ContractNet(travel)
            cnp_cpu, cnp_messages, cnp_failed = 0, 0, []
            for order in orders:
                allocation = cnp.allocate(order, copies)
                cnp_cpu += allocation.cpu_seconds
                cnp_messages += allocation.messages
                if allocation.vehicle_id is None:
                    cnp_failed.append(order.id)
            cnp_travel = sum(schedule(s, s.orders, travel).travel_seconds for s in copies)
            cnp_objective = cnp_travel + sum(
                100000 * priority_weight(o) for o in orders if o.id in cnp_failed)
            exact = exact_objective(states, orders, travel) if count == 4 else ''
            for limit in LIMITS:
                wall_start = perf_counter()
                result = CentralVRP(travel, limit).resolve(states, orders)
                wall = perf_counter() - wall_start
                rows.append(dict(seed=seed, orders=count, vehicles=len(states),
                                 limit_s=limit, objective=result.objective,
                                 travel_seconds=result.travel_seconds,
                                 failed=len(result.failed), cpu_s=result.cpu_seconds,
                                 wall_s=wall, messages=result.messages, status=result.status,
                                 exact_objective=exact, cnp_objective=cnp_objective,
                                 cnp_travel_seconds=cnp_travel, cnp_failed=len(cnp_failed),
                                 cnp_cpu_s=cnp_cpu, cnp_messages=cnp_messages))
    with (out/'time_limit_raw.csv').open('w', newline='', encoding='utf-8') as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    config = dict(limits_s=LIMITS, pilot_seeds=SEEDS, order_counts=[4, 30],
                  objective='open-route travel + priority-weighted drop penalties',
                  default_limit_s=2.0, drop_penalty=100000, threads=1,
                  priority_convention='1=HIGH, 2=MEDIUM, 3=LOW; weight=4-tier')
    config_text = json.dumps(config, sort_keys=True, indent=2)
    (out/'study_config.json').write_text(config_text+'\n', encoding='utf-8')
    import platform
    import importlib.metadata
    manifest = dict(python=platform.python_version(), platform=platform.platform(),
                    ortools=importlib.metadata.version('ortools'),
                    config_sha256=hashlib.sha256(config_text.encode()).hexdigest())
    (out/'manifest.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
    lines = ['# R4 pilot: solver quality versus time budget', '',
             'Generated by `python -m src.allocation.study`. All rows are actual local runs.',
             'Synthetic Manhattan metric, static forecasts, open routes. Pilot seeds only.',
             'CPU includes model build/extraction; wall limit applies to OR-Tools search.', '',
             '| Orders | Budget s | Mean objective | Mean CPU s | Mean wall s | Drops |',
             '|---:|---:|---:|---:|---:|---:|']
    for count in (4, 30):
        for limit in LIMITS:
            group = [r for r in rows if r['orders'] == count and r['limit_s'] == limit]
            def mean(key): return sum(r[key] for r in group) / len(group)
            lines.append(f'| {count} | {limit} | {mean("objective"):.2f} | '
                         f'{mean("cpu_s"):.4f} | {mean("wall_s"):.4f} | {mean("failed"):.2f} |')
    lines += ['', '## Interpretation', '',
              'Use raw paired seed rows to assess quality changes. Longer independent runs',
              'are not guaranteed monotone; record regressions rather than sorting them away.',
              'Four-order cases have an exhaustive reference; 30-order cases do not.',
              'Two seconds is the explicit default for the R4 reference, subject to the',
              'whole-system performance budget. This pilot does not establish full-map',
              'near-optimality, a plateau at all scales, or the final project claim.',
              'Compare CNP travel AND dropped orders/objective; distance alone rewards drops.',
              'CPU timings vary by machine. Wall-time-limited search may vary across reruns.',
              'Keep these pilot seeds disjoint from the final experiment seeds.', '']
    (out/'time_limit_study.md').write_text('\n'.join(lines), encoding='utf-8')
    return rows


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', default='reports/r4')
    args = parser.parse_args()
    print(f'Wrote {len(run_study(args.output))} runs to {args.output}')
