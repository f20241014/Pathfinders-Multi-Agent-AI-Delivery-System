"""
R3 · Measure what each CSP technique prunes (Week 3 deliverable, table for the report).

    python -m src.kr.csp_benchmark --out reports/csp_pruning.csv --md docs/csp_pruning.md

Random instances on a Euclidean toy world (so the numbers do not depend on map loading):
n orders with time windows 400-1500 s wide opening between 06:00 and 06:42, m vehicles with
capacity 5-9 units and shift end 07:40, demand 1-4. Times are seconds since midnight.
Same instances for every configuration; mean over seeds; runs that hit the node limit are counted.
"""

from __future__ import annotations

import argparse
import csv
import math
import random
import statistics
from pathlib import Path

from .csp import AssignmentCSP
from .ontology import SIM_START_S as T0, Order, Vehicle

CONFIGS = {
    "BT (plain backtracking)": dict(mrv=False, fc=False, ac3=False, lcv=False),
    "BT + MRV": dict(mrv=True, fc=False, ac3=False, lcv=False),
    "BT + MRV + FC": dict(mrv=True, fc=True, ac3=False, lcv=False),
    "BT + MRV + FC + AC-3 (root)": dict(mrv=True, fc=True, ac3=True, lcv=False),
    "BT + MRV + FC + AC-3 + LCV": dict(mrv=True, fc=True, ac3=True, lcv=True),
    "MAC (AC-3 every step) + MRV + LCV": dict(mrv=True, fc=True, ac3=True, lcv=True, mac=True),
}


def instance(seed: int, n: int, m: int):
    rng = random.Random(seed)
    pts = {i: (rng.random() * 4000, rng.random() * 4000) for i in range(80)}

    def tt(a, b, t):
        return math.dist(pts[a], pts[b]) / 8.0

    vehicles = [Vehicle(f"V{i}", 0, rng.randint(5, 9), shift_end=T0 + 6000) for i in range(m)]
    orders = []
    for i in range(n):
        s = T0 + rng.uniform(0, 2500)
        orders.append(
            Order(
                f"O{i}",
                rng.randint(1, 79),
                rng.randint(1, 4),
                rng.randint(1, 3),
                tw_start=s,
                tw_end=s + rng.uniform(400, 1500),
                service_time=120,
                release_time=T0,
            )
        )
    return vehicles, orders, tt


def run(sizes, seeds, node_limit):
    rows = []
    for n, m in sizes:
        for name, cfg in CONFIGS.items():
            nodes, checks, secs, hits, feas = [], [], [], 0, 0
            for seed in range(seeds):
                v, o, tt = instance(seed, n, m)
                r = AssignmentCSP(v, o, tt).solve(node_limit=node_limit, **cfg)
                nodes.append(r.stats.nodes)
                checks.append(r.stats.global_checks)
                secs.append(r.stats.seconds)
                hits += r.stats.limit_hit
                feas += r.feasible
            rows.append(
                dict(
                    orders=n,
                    vehicles=m,
                    config=name,
                    mean_nodes=round(statistics.mean(nodes), 1),
                    median_nodes=statistics.median(nodes),
                    mean_constraint_checks=round(statistics.mean(checks), 1),
                    mean_ms=round(1000 * statistics.mean(secs), 2),
                    limit_hits=hits,
                    feasible=feas,
                    seeds=seeds,
                )
            )
    return rows


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=30)
    ap.add_argument("--node-limit", type=int, default=100_000)
    ap.add_argument("--out", default="reports/csp_pruning.csv")
    ap.add_argument("--md", default="docs/csp_pruning.md")
    a = ap.parse_args()
    rows = run([(8, 3), (10, 3), (12, 4)], a.seeds, a.node_limit)
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    with open(a.out, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    header = ["Orders x vehicles", "Configuration", "Mean nodes", "Median nodes",
              "Mean constraint checks", "Mean ms", "Hit node limit", "Feasible"]
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    for r in rows:
        cells = [f"{r['orders']} x {r['vehicles']}", r["config"], r["mean_nodes"],
                 r["median_nodes"], r["mean_constraint_checks"], r["mean_ms"],
                 f"{r['limit_hits']}/{r['seeds']}", f"{r['feasible']}/{r['seeds']}"]
        lines.append("| " + " | ".join(str(c) for c in cells) + " |")
    Path(a.md).parent.mkdir(parents=True, exist_ok=True)
    Path(a.md).write_text(
        "# CSP pruning: nodes visited per technique\n\n"
        "Generated by `python -m src.kr.csp_benchmark --out reports/csp_pruning.csv "
        f"--md docs/csp_pruning.md` ({a.seeds} seeds per row, node limit {a.node_limit}).\n"
        "Nodes = values tried in the search tree. Constraint checks = global (n-ary) "
        "feasibility checks actually computed.\n\n"
        + "\n".join(lines)
        + "\n"
    )
    print("\n".join(lines))


if __name__ == "__main__":
    main()